export function substanceById(id: string): Substance | null {
  return substances.find((item) => item.id === id) ?? null;
}

/** ค้นจากชื่อที่ผู้ใช้เห็นบนฉลากหรือในเนื้อหา ไม่ใช่จาก id */
export function findSubstance(query: string): Substance | null {
  const needle = query.trim().toLowerCase();
  if (!needle) return null;
  return (
    substances.find(
      (item) =>
        item.name.toLowerCase() === needle ||
        item.aka.some((alias) => alias.toLowerCase() === needle),
    ) ?? null
  );
}
